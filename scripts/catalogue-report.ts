/**
 * Regenerates docs/CATALOGUE_REGISTER.md and docs/catalogue/reset-catalogue.json from src/content/reset-catalogue.ts.
 * Usage: npm run catalogue:report
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { RESET_CATALOGUE, UNUSED_SUPPLIED_IMAGES, BRIEF_REVIEW_NOTE, catalogueGaps } from '../src/content/reset-catalogue';

const root = join(__dirname, '..');
const log: Record<string, { src: string; srcSize: number[]; mode: string; scale: number; kb: number; limitedUpscale: boolean }> = JSON.parse(readFileSync(join(root, 'assets/product-masters/processing-log.json'), 'utf8'));
const naira = (n: number) => `₦${n.toLocaleString('en-NG')}`;
const esc = (s: string | null | undefined) => (s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');
const sha = (f: string) => createHash('sha256').update(readFileSync(f)).digest('hex').slice(0, 12);

const withPhoto = RESET_CATALOGUE.filter((p) => p.photo);
const out: string[] = [];
const w = (s = '') => out.push(s);

w('# Catalogue register');
w();
w('*Generated by `npm run catalogue:report` from `src/content/reset-catalogue.ts`. Do not edit by hand; change the catalogue file and regenerate.*');
w();
w('## 1. Summary');
w();
w(`- Products in the catalogue: **${RESET_CATALOGUE.length}** (brief entries 1–24). Entry 25 (“${BRIEF_REVIEW_NOTE}”) is a review note and is **not** a product; it was checked for duplicates and not created.`);
w(`- With a pack photograph: **${withPhoto.length}**. Without: **${RESET_CATALOGUE.length - withPhoto.length}** (no authentic photo was supplied; no AI-generated or stand-in packaging is used).`);
w(`- Label information verified: **${RESET_CATALOGUE.filter((p) => p.infoStatus === 'VERIFIED').length}**; provisional: **${RESET_CATALOGUE.filter((p) => p.infoStatus === 'PROVISIONAL').length}**; awaiting: **${RESET_CATALOGUE.filter((p) => p.infoStatus === 'AWAITING').length}**. Only verified text is shown publicly.`);
w(`- NAFDAC numbers verified: **0** of ${RESET_CATALOGUE.length}. None was visible on a supplied pack or published by the Nigerian retailers consulted; the field is empty rather than guessed.`);
w(`- Prices confirmed by the pharmacy: **0** of ${RESET_CATALOGUE.length}. All are provisional sample prices from the brief.`);
w(`- Photo permission confirmed by the owner: **0** of ${withPhoto.length}. All were supplied to us; the original publishers are not recorded.`);
w(`- Classified “pharmacist only” (not sold through the basket): ${RESET_CATALOGUE.filter((p) => p.cls === 'PHARMACY_ONLY').map((p) => `${p.no} ${p.name}`).join('; ')}.`);
w();
w('## 2. Product register');
w();
w('| No. | SKU | Product | Brand | Category | Sold as | Pack | Sample price | Photo | Label info |');
w('|---|---|---|---|---|---|---|---|---|---|');
for (const p of RESET_CATALOGUE) w(`| ${p.no} | ${p.sku} | ${esc(p.name)} | ${esc(p.brand) || '*awaiting brand confirmation*'} | ${p.cat} | ${p.cls === 'OTC' ? 'Over the counter' : 'Pharmacist only'} | ${esc(p.packSize) || '—'} | ${naira(p.naira)} | ${p.photo ? 'Yes' : '**None**'} | ${p.infoStatus.toLowerCase()} |`);
w();
w('## 3. Image source and licensing register');
w();
w('Every photograph below was **supplied to us by the client** (Maxwell, Dindu Digitals) on 24 Oct 2026 as a product picture. The original website or photographer was not recorded, so **permission to reuse is not confirmed for any of them**. They are bundled in `public/products/` (no hotlinking) and flagged `CLIENT_SUPPLIED` in the database and admin console.');
w();
w('The shell in the build environment can reach only package registries, and the Nigerian pharmacy sites consulted (HealthPlus, GoMed) publish all-rights-reserved notices with no image-reuse terms, so no image was downloaded from any third-party site.');
w();
w('| No. | Product | Public file | Source file (upload) | Source size | Processing | Pack market | Rights status | Public file hash |');
w('|---|---|---|---|---|---|---|---|---|');
for (const p of withPhoto) {
  const slug = p.photo!.replace('/products/', '').replace('.webp', '');
  const l = log[slug];
  const file = join(root, 'public', p.photo!);
  const proc = l ? `${l.mode === 'mb-backdrop' ? 'studio backdrop whitened; ' : slug.startsWith('coldcap') ? 'speckled backdrop cleaned; ' : ''}trimmed, centred on 800×800 white, WebP q88${l.limitedUpscale ? '; low-resolution source, upscaled ≤1.25×' : ''}` : '—';
  w(`| ${p.no} | ${esc(p.name)} (${esc(p.brand)}) | \`${p.photo}\` | ${l?.src ?? '—'} | ${l ? `${l.srcSize[0]}×${l.srcSize[1]}` : '—'} | ${proc} | ${esc(p.packMarket)} | Client supplied; owner permission **not confirmed** | ${existsSync(file) ? sha(file) : 'MISSING'} |`);
}
w();
w('Lossless masters of every supplied image are in `assets/product-masters/` (outside `public/`, so they are not served). `assets/product-masters/process.py` reproduces the processing.');
w();
w('### Supplied but not used');
w();
for (const u of UNUSED_SUPPLIED_IMAGES) w(`- \`${u.file}\`: ${u.reason}`);
w('- The four lifestyle photographs sent with the product images (pharmacist at the counter, pills, nurse, two customers at a shelf) are brand photography, not product packshots, and were not added to the catalogue.');
w();
w('### To record when permission is obtained');
w();
w('For each photograph: who owns it (manufacturer, distributor or photographer), the written permission or licence, the date, and any attribution wording. Update **Photo permission** and **Where the photo came from** on the product in the admin console, or replace the photograph with one the pharmacy has taken itself (Products → the product → Picture).');
w();
w('## 4. Information verification register');
w();
w('Status meanings: **verified** = checked against the product’s own label or leaflet; **provisional** = from a retailer listing or another market’s leaflet, stored for staff but not shown as label text; **awaiting** = nothing checked.');
w();
for (const p of RESET_CATALOGUE) {
  w(`### ${p.no}. ${p.name}${p.brand ? ` (${p.brand})` : ''}`);
  w();
  w(`- **Status:** ${p.infoStatus.toLowerCase()}`);
  w(`- **Source and notes:** ${esc(p.infoSource)}`);
  w(`- **Manufacturer:** ${esc(p.manufacturer) || 'not confirmed'}  ·  **Strength:** ${esc(p.strength) || 'not confirmed'}  ·  **Active ingredients:** ${esc(p.activeIngredients) || 'not confirmed'}`);
  w(`- **Directions:** ${p.howToUse ? (p.infoStatus === 'VERIFIED' ? 'verified, shown publicly' : 'stored, **not shown publicly**') : 'none'}  ·  **Warnings:** ${p.warnings ? (p.infoStatus === 'VERIFIED' ? 'verified, shown publicly' : 'stored, **not shown publicly**') : 'none'}  ·  **Storage:** ${p.storage ? 'stored' : 'none'}`);
  w(`- **NAFDAC number:** not verified`);
  w();
}
w('## 5. Missing and unverified information report');
w();
w('Everything below needs a decision or a document from the pharmacy before the entry is complete. Entries are listed in catalogue order.');
w();
for (const p of RESET_CATALOGUE) {
  w(`**${p.no}. ${p.name}** (${p.sku})`);
  w();
  for (const t of p.toConfirm) w(`- ${t}`);
  w();
}
w('### Applies to every product');
w();
w('- Confirm the exact pack the pharmacy stocks matches the photograph (several photographed packs are foreign-market packs; see “Pack market” above).');
w('- Confirm the NAFDAC registration number from the pack or the NAFDAC register and enter it in the product record.');
w('- Confirm the selling price (all are provisional sample prices) and tick “Price confirmed”. The shop will not publish a live product until this is done.');
w('- Pharmacist sign-off on the “sold as” classification, in particular the three items set conservatively to pharmacist only (nos. 1, 15, 21).');
w();
w('## 6. Gaps by field');
w();
w('| No. | Product | Gaps |');
w('|---|---|---|');
for (const p of RESET_CATALOGUE) w(`| ${p.no} | ${esc(p.name)} | ${catalogueGaps(p).join('; ')} |`);
w();
writeFileSync(join(root, 'docs/CATALOGUE_REGISTER.md'), out.join('\n') + '\n');
writeFileSync(join(root, 'docs/catalogue/reset-catalogue.json'), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), briefReviewNote: BRIEF_REVIEW_NOTE, unusedSuppliedImages: UNUSED_SUPPLIED_IMAGES, products: RESET_CATALOGUE }, null, 2) + '\n');
console.log(`Wrote docs/CATALOGUE_REGISTER.md (${statSync(join(root, 'docs/CATALOGUE_REGISTER.md')).size} bytes) and docs/catalogue/reset-catalogue.json`);
